"""
A. CONCEPTUAL QUESTIONS

1. EASY: Why do we unit-normalize embeddings before storing them in vector databases?
   - Answer: Unit-normalizing a vector sets its magnitude (L2 Norm) to exactly 1.0. 
     Mathematically, when both vectors $A$ and $B$ are normalized ($||A||=||B||=1$), 
     their Cosine Similarity is equivalent to their Dot Product ($\cos(A,B) = A \cdot B$). 
     This allows vector databases to execute dot-products (simple multiply-add SIMD operations) 
     directly without performing expensive square-root norm divisions during inference.

2. MEDIUM: Explain the scaling and accuracy trade-offs of Bi-Encoders vs. Cross-Encoders.
   - Answer:
     - Bi-Encoders: Embed queries and documents separately. This allows documents to be 
       pre-embedded and indexed in an ANN vector database. Similarity is evaluated in 
       O(1) search index time, which scales to billions of documents. However, it cannot 
       capture fine-grained token-level cross-attention.
     - Cross-Encoders: Pass both the query and document together into the transformer's 
       attention layers. This allows full token-level cross-attention, yielding much higher 
       relevance scoring. However, you cannot pre-compute embeddings; every query requires 
       evaluating the transformer on all document pairs, which is too slow for large-scale 
       retrieval. Hence, Bi-encoders retrieve candidate docs and Cross-encoders rerank the top 100.

3. HARD: Define the three evaluation metrics of the RAG Triad. How do we measure them?
   - Answer:
     - Faithfulness (Groundedness): Is the generated answer supported *only* by retrieved context? 
       Measurement: LLM-as-a-Judge splits response into claims, then evaluates if each claim 
       is supported by the retrieved context.
     - Answer Relevance: Does the generated answer address the user query? 
       Measurement: Ask LLM-as-a-Judge to synthesize hypothetical queries matching the generated 
       answer, then compute cosine similarity between the generated queries and the user query.
     - Context Recall (Relevance): Did the retriever fetch the correct material to answer the query? 
       Measurement: Evaluate the semantic overlap between ground-truth reference material 
       and retrieved chunks.

B. LIVE CODING EXERCISES

1. EXERCISE: Implement a function `verify_normalized_cosine_equivalence(v1, v2)` that takes 
   two 1D arrays, unit-normalizes them, and proves that their Dot Product is equal to their 
   Cosine Similarity.
   - Code Template to execute:
"""

def verify_normalized_cosine_equivalence(v1: np.ndarray, v2: np.ndarray) -> tuple:
    # 1. Calculate traditional Cosine Similarity: A . B / (||A|| * ||B||)
    dot_prod = np.dot(v1, v2)
    norm_v1 = np.linalg.norm(v1)
    norm_v2 = np.linalg.norm(v2)
    traditional_cosine = dot_prod / (norm_v1 * norm_v2)

    # 2. Unit-normalize both vectors
    v1_normed = v1 / norm_v1
    v2_normed = v2 / norm_v2

    # 3. Calculate Dot Product of normalized vectors
    normalized_dot = np.dot(v1_normed, v2_normed)

    return traditional_cosine, normalized_dot


