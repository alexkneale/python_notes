"""
1. What is RAG (Retrieval-Augmented Generation)?
   - Large Language Models (LLMs) are trained on a snapshot of data and can hallucinate. 
     RAG solves this by first retrieving relevant documents from a local database matching 
     a user's query, and then pasting those documents into the LLM's prompt context so 
     it can synthesize an accurate, fact-grounded response.
2. What is a Vector Embedding?
   - An embedding is a list of numbers (a vector) generated by a specialized model that 
     represents the semantic meaning of a word, sentence, or document. Words with similar 
     meanings (e.g. "king" and "queen") will have vectors that point in highly similar 
     directions in space.
3. What is a Vector Database?
   - A vector database stores these numeric embeddings and indexes them using fast search 
     algorithms so that we can find semantically relevant documents in milliseconds.
"""



import numpy as np

# ============================================================================
# 1. RETRIEVAL-GENERATION DECOUPLING: HIERARCHICAL & SEMANTIC CHUNKING
# ============================================================================
"""
Naive RAG chunks text into uniform sizes (e.g. 512 tokens with 10% overlap).
This creates a critical trade-off:
- Small Chunks (e.g. 100 tokens): Yield highly focused embeddings. Vector search 
  finds precise sentences, but the LLM lacks the surrounding context needed 
  to synthesize an accurate answer, leading to half-truths or hallucinations.
- Large Chunks (e.g. 2000 tokens): Contain complete context for the LLM, 
  but dilute the vector search signal because the semantic vector is averaged 
  over diverse topics.

The Solution: Hierarchical (Parent-Child) Chunking
- We split the document into large 'Parent' chunks (e.g., 1000 tokens).
- We split each Parent chunk into several small 'Child' chunks (e.g., 150 tokens).
- We embed and perform vector search ONLY on the Child chunks.
- Upon retrieving a child chunk, we fetch its corresponding Parent chunk 
  and pass the Parent chunk to the LLM. 
  This decouples the chunk used for semantic lookup from the chunk used for generation!
"""


# ============================================================================
# 2. VECTOR INDEXING MECHANICS: HNSW VS IVF
# ============================================================================
"""
For enterprise scale (millions of vectors), flat O(N) cosine similarity is too slow.
We use Approximate Nearest Neighbor (ANN) index structures:

A. IVF-FLAT (Inverted File Index):
   - We cluster the vector space into K clusters using K-Means.
   - For an incoming query, we only compute distances to the centroids of clusters, 
     then search inside the closest 'n_probe' clusters.
   - Speed: O(K + n_probe * N/K) instead of O(N).

B. HNSW (Hierarchical Navigable Small World):
   - A multi-layer graph-based index structure.
   - Top layers have skip-connections (sparse graph) for quick long-range routing.
   - Bottom layers are dense graphs containing all vectors for precise local search.
   - Speed: O(log N). Highly accurate but memory-intensive (needs to hold graphs in RAM).

Vector Distance Metrics:
- Cosine Similarity: Cos(A, B) = A . B / (||A|| * ||B||)
- Dot Product: Dot(A, B) = A . B
- IMPORTANT: If your vectors are Unit-Normalized (length ||A|| = 1), Cosine 
  Similarity is mathematically identical to Dot Product! 
  Normalizing vectors beforehand lets database engines use simple, blazing-fast 
  MADD (Multiply-Add) operations without expensive square-root norm divisions.
"""


# ============================================================================
# 3. HYBRID SEARCH: MANUALLY IMPLEMENTING RECIPROCAL RANK FUSION (RRF)
# ============================================================================
"""
Dense semantic search (Vector) is great for conceptual queries, but fails on 
precise keyword matches (product codes, specific names). Keyword search (BM25) 
is great for exact matches but misses synonyms.
Hybrid Search combines both. To merge their scores (since vector cosine scores 
and BM25 scores have completely different bounds), we use Reciprocal Rank Fusion (RRF).

RRF Score Formula:
    RRF_Score(doc_id) = sum_{m in Search_Models} [ 1 / (k + rank_m(doc_id)) ]

where:
- Search_Models = {Vector_Search, Keyword_BM25_Search}
- rank_m(doc_id) is the 1-based rank of the document in model m's results.
- k is a smoothing constant (usually 60) that prevents top ranks from 
  overwhelming lower ranks.
"""

def compute_reciprocal_rank_fusion(vector_results: list, keyword_results: list, k: int = 60) -> list:
    """
    vector_results: List of document IDs sorted from best to worst according to vector search.
    keyword_results: List of document IDs sorted from best to worst according to BM25.
    k: RRF hyperparameter.
    """
    rrf_scores = {}

    # 1. Process vector results
    for rank, doc_id in enumerate(vector_results, start=1):
        if doc_id not in rrf_scores:
            rrf_scores[doc_id] = 0.0
        rrf_scores[doc_id] += 1.0 / (k + rank)

    # 2. Process keyword results
    for rank, doc_id in enumerate(keyword_results, start=1):
        if doc_id not in rrf_scores:
            rrf_scores[doc_id] = 0.0
        rrf_scores[doc_id] += 1.0 / (k + rank)

    # 3. Sort documents by descending RRF score
    sorted_hybrid_results = sorted(rrf_scores.items(), key=lambda item: item[1], reverse=True)
    return sorted_hybrid_results


def demonstrate_rrf():
    print("\n" + "="*80)
    print("3. HYBRID SEARCH: RECIPROCAL RANK FUSION (RRF) RUNNABLE DEMO")
    print("="*80)

    # Suppose we search for: "Troubleshoot Cloud SQL replication error 109"
    # Document A contains precise keyword "error 109" but is not very conceptually detailed.
    # Document B discusses "Cloud SQL replication sync lag" conceptually but lacks exact code "109".
    # Document C is slightly relevant to both.

    # Ranks returned by different engines:
    vector_ranks = ["Doc_B", "Doc_C", "Doc_A", "Doc_D"]   # Vector favors concept B
    keyword_ranks = ["Doc_A", "Doc_E", "Doc_C", "Doc_B"]  # BM25 favors keyword A

    # Compute Hybrid results
    hybrid_results = compute_reciprocal_rank_fusion(vector_ranks, keyword_ranks, k=2) # Using small k=2 to highlight behavior

    print("Vector Search Ranks: ", vector_ranks)
    print("Keyword Search Ranks:", keyword_ranks)
    print("\nFused Hybrid Results (RRF):")
    for doc_id, score in hybrid_results:
        print(f"  {doc_id:10s} | RRF Score: {score:.5f}")

    print("\nNote: Doc_C rank is elevated in Hybrid because it appeared consistently high in both searches!")


